// Writes apps/customer/src/lib/logoPoints.ts: LOGO_POINTS target points inside the glyphs of the 826 mark, for the opening animation's smoke.
// Mitchell's best-candidate sampling over the alpha mask (blue noise, seeded, deterministic). Needs sharp, which is not a dependency here:
//   NODE_PATH=<a node_modules with sharp> node scripts/make-logo-points.mjs
import { createRequire } from 'module';
import { writeFileSync } from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const require = createRequire(import.meta.url);
const sharp = require('sharp');
const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const mark = path.join(root, 'apps/customer/assets/logo-mark.png');
const out = path.join(root, 'apps/customer/src/lib/logoPoints.ts');
const COUNT = 112;
const CANDIDATES = 40;
const INSET = 3; // px: a point must sit this far inside the glyph edge

const { data, info } = await sharp(mark).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
const { width: w, height: h, channels } = info;
const solid = (x, y) => {
    const xi = Math.floor(x);
    const yi = Math.floor(y);

    return xi >= 0 && yi >= 0 && xi < w && yi < h && data[(yi * w + xi) * channels + channels - 1] > 128;
};
const inside = (x, y) => {
    for (let a = 0; a < 8; a++) {
        if (!solid(x + Math.cos((a * Math.PI) / 4) * INSET, y + Math.sin((a * Math.PI) / 4) * INSET)) {
            return false;
        }
    }

    return solid(x, y);
};
let seed = 826;
const rand = () => {
    seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;

    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
};
const candidate = () => {
    for (;;) {
        const x = rand() * w;
        const y = rand() * h;
        if (inside(x, y)) {
            return [x, y];
        }
    }
};
const pts = [candidate()];
while (pts.length < COUNT) {
    let best = null;
    let bestD = -1;
    for (let k = 0; k < CANDIDATES; k++) {
        const c = candidate();
        const d = Math.min(...pts.map((p) => (p[0] - c[0]) ** 2 + (p[1] - c[1]) ** 2));
        if (d > bestD) {
            bestD = d;
            best = c;
        }
    }
    pts.push(best);
}
const rows = pts.map(([x, y]) => `    [${(x / w).toFixed(4)}, ${(y / h).toFixed(4)}],`).join('\n');
writeFileSync(out, `// GENERATED by scripts/make-logo-points.mjs from assets/logo-mark.png (${w}x${h}); do not edit. Blue-noise points inside the glyphs, x and y as 0..1 of the mark's box.\nexport const LOGO_POINTS: readonly (readonly [number, number])[] = [\n${rows}\n];\n`);
console.log('wrote', pts.length, 'points', 'min gap px', Math.sqrt(Math.min(...pts.flatMap((p, i) => pts.slice(i + 1).map((q) => (p[0] - q[0]) ** 2 + (p[1] - q[1]) ** 2)))).toFixed(1));
